import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

export const fixtureConfig = {
  screens: 32,
  rowsPerScreen: 8,
  metricsPerScreen: 4,
  themeColors: 240,
  rebuildClasses: 400,
};

const generatedDir = path.join(root, 'src', 'benchmark');

const hash = (value) => {
  let x = value | 0;
  x ^= x << 13;
  x ^= x >>> 17;
  x ^= x << 5;
  return x >>> 0;
};

const hex = (value) => hash(value).toString(16).padStart(8, '0').slice(0, 6);

const px = (seed, min, max) => min + (hash(seed) % (max - min + 1));

const themeClass = (kind, seed) => `${kind}-bench-${seed % fixtureConfig.themeColors}`;

const utilitySet = (seed) => [
  'group',
  'relative',
  'isolate',
  'grid',
  'overflow-hidden',
  'border',
  'transition-[transform,opacity,filter,box-shadow]',
  'will-change-transform',
  themeClass('bg', seed),
  themeClass('text', seed + 11),
  themeClass('border', seed + 23),
  themeClass('ring', seed + 31),
  themeClass('shadow', seed + 47),
  `grid-cols-[repeat(${(seed % 5) + 2},minmax(0,1fr))]`,
  `gap-[${px(seed + 1, 3, 28)}px]`,
  `rounded-[${px(seed + 2, 2, 34)}px]`,
  `p-[${px(seed + 3, 2, 30)}px]`,
  `min-h-[${px(seed + 4, 28, 220)}px]`,
  `outline-[${px(seed + 5, 1, 6)}px]`,
  `outline-[#${hex(seed + 6)}]`,
  `ring-[${px(seed + 7, 1, 7)}px]`,
  `blur-[${px(seed + 8, 0, 2)}px]`,
  `brightness-[${px(seed + 9, 75, 135)}%]`,
  `contrast-[${px(seed + 10, 80, 160)}%]`,
  `translate-x-[${px(seed + 12, -18, 18)}px]`,
  `translate-y-[${px(seed + 13, -18, 18)}px]`,
  `rotate-[${px(seed + 14, -12, 12)}deg]`,
  `duration-[${px(seed + 15, 80, 900)}ms]`,
  `delay-[${px(seed + 16, 0, 240)}ms]`,
  `hover:bg-[#${hex(seed + 17)}]`,
  `hover:text-[#${hex(seed + 18)}]`,
  `hover:shadow-[0_${px(seed + 19, 4, 28)}px_${px(seed + 20, 12, 72)}px_#${hex(seed + 21)}]`,
  `focus-within:ring-[#${hex(seed + 22)}]`,
  `md:grid-cols-[repeat(${(seed % 7) + 2},minmax(0,1fr))]`,
  `lg:p-[${px(seed + 24, 8, 46)}px]`,
  `xl:rounded-[${px(seed + 25, 8, 48)}px]`,
  `dark:bg-[#${hex(seed + 26)}]`,
  `dark:text-[#${hex(seed + 27)}]`,
  `group-hover:translate-y-[${px(seed + 28, -14, 14)}px]`,
  `data-[state=active]:scale-[${px(seed + 29, 97, 104)}%]`,
  `aria-[current=page]:font-[${px(seed + 30, 500, 900)}]`,
  `supports-[backdrop-filter:blur(0px)]:backdrop-blur-[${px(seed + 31, 2, 28)}px]`,
];

const compactClassName = (seed) => utilitySet(seed).join(' ');

const renderThemeCss = () => {
  const lines = [
    "/* This file is generated by scripts/generate-fixture.mjs. */",
    "@import 'tailwindcss';",
    "@source './benchmark';",
    '',
    '@theme {',
  ];

  for (let i = 0; i < fixtureConfig.themeColors; i += 1) {
    const color = hex(i * 19 + 5);
    const shadow = hex(i * 23 + 7);
    lines.push(`  --color-bench-${i}: #${color};`);
    lines.push(`  --shadow-bench-${i}: 0 ${1 + (i % 9)}px ${8 + (i % 36)}px rgb(${parseInt(shadow.slice(0, 2), 16)} ${parseInt(shadow.slice(2, 4), 16)} ${parseInt(shadow.slice(4, 6), 16)} / 0.28);`);
  }

  lines.push('}');
  lines.push('');
  lines.push(':root {');
  lines.push('  color-scheme: dark;');
  lines.push('  font-family: Inter, ui-sans-serif, system-ui, -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif;');
  lines.push('}');
  lines.push('');
  lines.push('body {');
  lines.push('  margin: 0;');
  lines.push('  background: #09090b;');
  lines.push('}');
  lines.push('');
  lines.push('* {');
  lines.push('  box-sizing: border-box;');
  lines.push('}');
  lines.push('');

  return `${lines.join('\n')}\n`;
};

const renderMetric = (screen, metric) => {
  const seed = screen * 997 + metric * 37;
  return `        <li className="${compactClassName(seed)}">
          <span className="text-[10px] font-semibold uppercase tracking-[0.2em] text-white/70">Metric ${metric + 1}</span>
          <strong className="mt-2 block text-[${px(seed + 2, 18, 34)}px] font-black leading-none text-white">${px(seed + 3, 1000, 9999)}</strong>
        </li>`;
};

const renderRow = (screen, row) => {
  const seed = screen * 1009 + row * 53;
  return `      <article className="${compactClassName(seed)}" data-state="${row % 3 === 0 ? 'active' : 'idle'}" aria-current={${row % 7 === 0 ? "'page'" : 'undefined'}}>
        <div className="${compactClassName(seed + 1)}">
          <span className="${compactClassName(seed + 2)}">S${screen.toString().padStart(3, '0')}.${row.toString().padStart(2, '0')}</span>
          <span className="${compactClassName(seed + 3)}">${hex(seed)}</span>
        </div>
        <div className="${compactClassName(seed + 4)}">
          <span className="${compactClassName(seed + 5)}" />
          <span className="${compactClassName(seed + 6)}" />
          <span className="${compactClassName(seed + 7)}" />
        </div>
      </article>`;
};

const renderScreen = (screen) => {
  const metrics = Array.from({ length: fixtureConfig.metricsPerScreen }, (_, index) =>
    renderMetric(screen, index),
  ).join('\n');
  const rows = Array.from({ length: fixtureConfig.rowsPerScreen }, (_, index) =>
    renderRow(screen, index),
  ).join('\n');
  const seed = screen * 811;

  return `function BenchmarkScreen${screen.toString().padStart(3, '0')}() {
  return (
    <section className="${compactClassName(seed)}">
      <header className="${compactClassName(seed + 1)}">
        <div>
          <p className="text-xs font-semibold uppercase tracking-[0.32em] text-white/60">Scenario ${screen + 1}</p>
          <h2 className="mt-2 text-[${px(seed + 2, 20, 38)}px] font-black leading-none text-white">Synthetic product surface ${screen + 1}</h2>
        </div>
        <button className="${compactClassName(seed + 3)}" type="button">Inspect</button>
      </header>
      <ul className="${compactClassName(seed + 4)}">
${metrics}
      </ul>
      <div className="${compactClassName(seed + 5)}">
${rows}
      </div>
    </section>
  );
}`;
};

const renderComponents = () => {
  const screens = Array.from({ length: fixtureConfig.screens }, (_, index) =>
    renderScreen(index),
  );
  const nodes =
    fixtureConfig.screens *
    (5 + fixtureConfig.metricsPerScreen * 3 + fixtureConfig.rowsPerScreen * 8);
  const classTokens =
    fixtureConfig.screens *
    (6 + fixtureConfig.metricsPerScreen + fixtureConfig.rowsPerScreen * 7) *
    utilitySet(1).length;

  return `/* This file is generated by scripts/generate-fixture.mjs. */
import type { ReactNode } from 'react';

${screens.join('\n\n')}

export const benchmarkStats = {
  screens: ${fixtureConfig.screens},
  rowsPerScreen: ${fixtureConfig.rowsPerScreen},
  metricsPerScreen: ${fixtureConfig.metricsPerScreen},
  nodes: ${nodes},
  classTokens: ${classTokens},
};

const screens: ReactNode[] = [
${Array.from({ length: fixtureConfig.screens }, (_, index) => `  <BenchmarkScreen${index.toString().padStart(3, '0')} key="screen-${index}" />,`).join('\n')}
];

export function BenchmarkForest() {
  return <div className="grid gap-5">{screens}</div>;
}
`;
};

export const renderRebuildTarget = (seed = 0) => {
  const classes = Array.from({ length: fixtureConfig.rebuildClasses }, (_, index) =>
    compactClassName(seed * 100000 + index * 41),
  ).join(' ');

  return `/* This file is generated by scripts/generate-fixture.mjs. */
export const rebuildToken = '${seed.toString().padStart(4, '0')}';

export function RebuildTarget() {
  return (
    <div className="${classes}" data-state="active" aria-current="page">
      <div className="grid gap-2 text-xs text-white/70">
        <span>Seed {rebuildToken}</span>
        <span>Classes ${fixtureConfig.rebuildClasses.toLocaleString()}</span>
      </div>
    </div>
  );
}
`;
};

export async function writeRebuildTarget(seed = 0) {
  await mkdir(generatedDir, { recursive: true });
  await writeFile(
    path.join(generatedDir, 'rebuild-target.tsx'),
    renderRebuildTarget(seed),
  );
}

export async function generateFixture() {
  await mkdir(generatedDir, { recursive: true });
  await writeFile(path.join(root, 'src', 'styles.css'), renderThemeCss());
  await writeFile(
    path.join(generatedDir, 'generated-components.tsx'),
    renderComponents(),
  );
  await writeRebuildTarget(0);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await generateFixture();
  console.log(
    `Generated ${fixtureConfig.screens} screens and ${fixtureConfig.rebuildClasses} rebuild class groups.`,
  );
}
