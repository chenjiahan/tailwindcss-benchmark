export const renderRebuildTarget = (seed = 0) => {
  const classes = Array.from({ length: fixtureConfig.rebuildClasses }, (_, index) =>
    compactClassName(seed * 100000 + index * 41),
  ).join(' ');

  return `/* This file is generated by scripts/generate-fixture.mjs. */
export const rebuildToken = '${seed.toString().padStart(4, '0')}';

export function RebuildTarget() {
  return (
    <div className="${classes}" data-state="active" aria-current="page">
      <div className="grid gap-2 text-xs text-white/70">
        <span>Seed {rebuildToken}</span>
        <span>Classes ${fixtureConfig.rebuildClasses.toLocaleString()}</span>
      </div>
    </div>
  );
}
`;
};

export async function writeRebuildTarget(seed = 0) {
  await mkdir(benchmarkDir, { recursive: true });
  await writeFile(
    path.join(benchmarkDir, 'rebuild-target.tsx'),
    renderRebuildTarget(seed),
  );
}

export async function generateFixture() {
  await rm(generatedDir, { recursive: true, force: true });
  await rm(path.join(benchmarkDir, 'generated-components.tsx'), {
    force: true,
  });
  await mkdir(generatedDir, { recursive: true });
  await writeFile(path.join(root, 'src', 'styles.css'), renderThemeCss());
  const sharedComponents = renderSharedComponents();
  await Promise.all(
    Object.entries(sharedComponents).map(async ([relativePath, content]) => {
      const filePath = path.join(generatedDir, relativePath);
      await mkdir(path.dirname(filePath), { recursive: true });
      await writeFile(filePath, content);
    }),
  );
  await writeFile(path.join(generatedDir, 'index.tsx'), renderIndex());
  await writeFile(path.join(generatedDir, 'registry.tsx'), renderRegistry());
  await Promise.all(
    Array.from({ length: fixtureConfig.screens }, async (_, index) => {
      const name = index.toString().padStart(3, '0');
      const screenDir = path.join(generatedDir, 'screens', `screen-${name}`);
      await mkdir(screenDir, { recursive: true });
      await writeFile(path.join(screenDir, 'ActivityFeed.tsx'), renderActivityFeed(index));
      await writeFile(path.join(screenDir, 'MetricGrid.tsx'), renderMetricGrid(index));
      await writeFile(path.join(screenDir, 'Screen.tsx'), renderScreen(index));
    }),
  );
  await writeRebuildTarget(0);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await generateFixture();
  console.log(
    `Generated ${fixtureConfig.screens} screens across ${fixtureConfig.screens * fixtureConfig.screenModules + fixtureConfig.sharedModules} modules and ${fixtureConfig.rebuildClasses} rebuild class groups.`,
  );
}
